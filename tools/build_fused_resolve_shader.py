#!/usr/bin/env python3
"""Build the experimental RGBA8 fused resolve shader with DXC.

Usage: build_fused_resolve_shader.py --dxc /path/to/dxc
The generated DXIL header is checked in so regular builds do not need DXC.
"""
from __future__ import annotations

import argparse
import pathlib
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
SHADER_DIR = ROOT / "src/graphics/shaders/fused_resolve"
SOURCE = SHADER_DIR / "resolve_fast_32bpp_1x2xmsaa_fused.cs.xesl"
OUTPUT = ROOT / "src/graphics/shaders/bytecode/d3d12_6_0/resolve_fast_32bpp_1x2xmsaa_fused_cs.h"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dxc", required=True, type=pathlib.Path)
    args = parser.parse_args()
    dxc = args.dxc.resolve()
    version = subprocess.check_output([str(dxc), "--version"], text=True).strip()
    with tempfile.TemporaryDirectory(prefix="tek6-fused-shader-") as temporary:
        binary = pathlib.Path(temporary) / "fused.dxil"
        command = [str(dxc), "-T", "cs_6_0", "-HV", "2017", "-D",
                   "SHADING_LANGUAGE_HLSL_XE=1", "-I", str(SHADER_DIR),
                   "-Fo", str(binary), str(SOURCE)]
        subprocess.run(command, check=True)
        data = binary.read_bytes()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    name = "resolve_fast_32bpp_1x2xmsaa_fused_cs"
    lines = ["// Generated by tools/build_fused_resolve_shader.py.",
             f"// Compiler: {version}", "#pragma once", "", "#include <cstddef>",
             "#include <cstdint>", "",
             f"alignas(4) inline constexpr uint8_t {name}[] = {{"]
    for offset in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{value:02X}" for value in data[offset:offset + 16]) + ",")
    lines.extend(["};", f"inline constexpr size_t {name}_size = sizeof({name});", ""])
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
